#!/usr/bin/env python
"""Regenerate the astropy reference fixture the client's TAN code is tested against.

The viewer implements the TAN (gnomonic) projection in JavaScript so it can map
cursor position to sky coordinates without a FITS library. That is a second
implementation of a formula that is easy to get subtly wrong, so it is checked
against astropy rather than against itself:

    sidecar/.venv/bin/python sidecar/make_tan_fixture.py

The output is written to client/src/lib/fixtures/spherex-nep-tan.json and
committed. Nothing in the app reads it at runtime — only the client unit tests.
"""

import json
import math
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))

from reproject_common import build_target_grid  # noqa: E402

REPO = pathlib.Path(__file__).resolve().parent.parent
GRID = REPO / "data" / "spherex" / "common-grid.json"
OUT = REPO / "client" / "src" / "lib" / "fixtures" / "spherex-nep-tan.json"

# Pixel samples: corners, edges, the reference pixel, and a few arbitrary
# positions. 0-based, as astropy's pixel_to_world_values expects.
PIXELS = [
    [0.0, 0.0],
    [293.0, 293.0],
    [0.0, 293.0],
    [293.0, 0.0],
    [146.5, 146.5],  # the CRPIX (147.5, 147.5) reference pixel, 0-based
    [12.5, 250.75],
    [3.0, 4.0],
    [293.0, 146.5],
]

# Sky samples: the field centre, offsets by whole pixels along each axis, and
# two points outside the grid entirely (the projection must stay well behaved).
SKY = [
    [270.0, 66.5],
    [270.0, 66.505],
    [269.9, 66.5],
    [271.5, 67.0],
    [265.0, 60.0],
    [280.0, 70.0],
]


def main():
    spec = json.loads(GRID.read_text())
    wcs, _shape = build_target_grid(
        {
            "ra": spec["ra"],
            "dec": spec["dec"],
            "pixel_scale_arcsec": spec["pixel_scale_arcsec"],
            "shape": spec["shape"],
            "rotation_deg": spec["rotation_deg"],
        }
    )

    world = wcs.pixel_to_world_values(
        [p[0] for p in PIXELS], [p[1] for p in PIXELS]
    )
    pixels = wcs.world_to_pixel_values(
        [s[0] for s in SKY], [s[1] for s in SKY]
    )

    fixture = {
        "schema": "novochar.client.tan-fixture/v1",
        "grid": {
            "ra": spec["ra"],
            "dec": spec["dec"],
            "pixel_scale_arcsec": spec["pixel_scale_arcsec"],
            "shape": spec["shape"],
            "rotation_deg": spec["rotation_deg"],
        },
        "note": (
            "Generated by astropy (sidecar/make_tan_fixture.py) from the same "
            "build_target_grid the sidecar used for M3-B. Pixel coordinates are "
            "0-based; sky coordinates are ICRS degrees."
        ),
        "pixel_to_sky": [
            {"x": p[0], "y": p[1], "ra": float(r), "dec": float(d)}
            for p, r, d in zip(PIXELS, world[0], world[1])
        ],
        "sky_to_pixel": [
            {"ra": s[0], "dec": s[1], "x": float(x), "y": float(y)}
            for s, x, y in zip(SKY, pixels[0], pixels[1])
        ],
    }

    # A round-trip here is what the JS side must also achieve; if astropy
    # cannot do it, the fixture itself is suspect.
    for row in fixture["sky_to_pixel"]:
        back = wcs.pixel_to_world_values(row["x"], row["y"])
        assert math.hypot(float(back[0]) - row["ra"], float(back[1]) - row["dec"]) < 1e-9

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(json.dumps(fixture, indent=2) + "\n")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
